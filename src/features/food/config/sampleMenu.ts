export function getProductFallbackImage(productId?: string, categoryId?: string, name?: string): string {
  if (productId) {
    const item = SAMPLE_FOOD_MENU.find(p => p.id === productId);
    if (item?.image) return item.image;
  }
  const cleanName = (name || '').toLowerCase();
  if (cleanName.includes('dum biryani')) return '/images/food/chicken_dum_biryani.jpg';
  if (cleanName.includes('fry biryani')) return '/images/food/chicken_fry_biryani.jpg';
  if (cleanName.includes('mughalai')) return '/images/food/chicken_mughalai_biryani.jpg';
  if (cleanName.includes('paneer biryani')) return '/images/food/paneer_biryani.jpg';
  if (cleanName.includes('mushroom biryani')) return '/images/food/mushroom_biryani.jpg';
  if (cleanName.includes('prawn biryani')) return '/images/food/prawn_biryani.jpg';
  if (cleanName.includes('fried rice')) return '/images/food/chicken_fried_rice.jpg';
  if (cleanName.includes('noodle')) return '/images/food/chicken_noodles.jpg';
  if (cleanName.includes('manchurian')) return '/images/food/chicken_manchurian.jpg';
  if (cleanName.includes('65')) return '/images/food/chicken_65.jpg';
  if (cleanName.includes('chilli')) return '/images/food/chilli_chicken.jpg';
  if (cleanName.includes('pepper')) return '/images/food/pepper_chicken_dry.jpg';
  return '/images/food/chopsticks_cover.webp';
}

export function getFoodProductById(id: string): FoodProduct | undefined {
  return SAMPLE_FOOD_MENU.find(p => p.id === id);
}
